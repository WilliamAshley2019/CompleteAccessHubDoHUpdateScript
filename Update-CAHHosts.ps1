<#
.SYNOPSIS
    Resolves all hostnames required by Complete Access Hub and updates the
    Windows hosts file with current IP addresses.

.DESCRIPTION
    - Queries a DoH resolver (Cloudflare, hardcoded to 1.1.1.1) so it works
      even when the system resolver is broken.
    - Removes previously managed entries (between marker comments).
    - Appends fresh entries at the bottom.
    - Flushes DNS cache afterwards.

.NOTES
    Must be run as Administrator (writes to system hosts file).
#>

[CmdletBinding()]
param(
    [switch]$DryRun
)

$ErrorActionPreference = 'Stop'

# ---------------------------------------------------------------
# Config
# ---------------------------------------------------------------
$HostsPath   = "$env:SystemRoot\System32\drivers\etc\hosts"
$BackupDir   = Join-Path $env:ProgramData 'CAHHostsUpdater\Backups'
$LogPath     = Join-Path $env:ProgramData 'CAHHostsUpdater\updater.log'
$StartMarker = '# === CAH MANAGED BLOCK START ==='
$EndMarker   = '# === CAH MANAGED BLOCK END ==='

# Hostnames required by Complete Access Hub.
# Cloudflare DoH IP is used (1.1.1.1) so this works even when system DNS fails.
$DoHServer = '1.1.1.1'

$Hostnames = @(
    'app.completeaccess.audio'
    'cah-data.slatedigital.com'
    'app.slatedigital.com'
    'ilok.com'
    'api.sonible.com'
    'dispatcher.sonible.com'
    'api.solidstatelogic.com'
    'softwareupdate.solidstatelogic.com'
    'cdn.virtu-desktop.slatedigital.com'
    'cdn2.slatedigital.com'
)

# Hostnames we intentionally blackhole (telemetry, optional)
$BlockHostnames = @(
    'www.google-analytics.com'
)

# ---------------------------------------------------------------
# Ensure dirs
# ---------------------------------------------------------------
foreach ($d in @($BackupDir, (Split-Path $LogPath))) {
    if (-not (Test-Path -LiteralPath $d)) {
        New-Item -ItemType Directory -Path $d -Force | Out-Null
    }
}

function Write-Log {
    param([string]$Message, [string]$Level = 'INFO')
    $line = "[{0}] [{1}] {2}" -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'), $Level, $Message
    Add-Content -LiteralPath $LogPath -Value $line
    Write-Host $line
}

# ---------------------------------------------------------------
# Check admin
# ---------------------------------------------------------------
$isAdmin = ([Security.Principal.WindowsPrincipal] `
    [Security.Principal.WindowsIdentity]::GetCurrent()
).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)

if (-not $isAdmin) {
    Write-Log 'Not running as Administrator. Re-launching elevated...' 'WARN'
    $argList = @(
        '-NoProfile','-ExecutionPolicy','Bypass',
        '-File', "`"$PSCommandPath`""
    )
    if ($DryRun) { $argList += '-DryRun' }
    Start-Process -FilePath 'powershell.exe' -ArgumentList $argList -Verb RunAs -Wait
    exit $LASTEXITCODE
}

# ---------------------------------------------------------------
# DoH resolver
# ---------------------------------------------------------------
function Resolve-WithDoH {
    param(
        [string]$Name,
        [int]$Type = 1   # 1=A, 28=AAAA
    )
    $url = "https://$DoHServer/dns-query?name=$Name&type=$Type"
    try {
        $resp = Invoke-RestMethod -Uri $url -Headers @{
            Accept = 'application/dns-json'
        } -TimeoutSec 10
        return @($resp.Answer | Where-Object { $_.type -eq $Type } |
                 ForEach-Object { $_.data })
    } catch {
        Write-Log "DoH lookup failed for $Name (type $Type): $($_.Exception.Message)" 'WARN'
        return @()
    }
}

# ---------------------------------------------------------------
# Resolve all hostnames
# ---------------------------------------------------------------
Write-Log 'Resolving hostnames via DoH...'

$resolved = @{}   # hostname -> [list of IPv4]

foreach ($name in $Hostnames) {
    $ips = Resolve-WithDoH -Name $name -Type 1
    if ($ips.Count -gt 0) {
        $resolved[$name] = $ips
        Write-Log ("  {0} -> {1}" -f $name, ($ips -join ', '))
    } else {
        Write-Log "  $name -> NO IPv4 RECORDS" 'WARN'
    }
}

if ($resolved.Count -eq 0) {
    Write-Log 'No hostnames resolved. Aborting without touching hosts file.' 'ERROR'
    exit 1
}

# ---------------------------------------------------------------
# Build new managed block
# ---------------------------------------------------------------
$timestamp = Get-Date -Format 'yyyy-MM-dd HH:mm:ss'
$newBlock = New-Object System.Collections.Generic.List[string]
$newBlock.Add($StartMarker)
$newBlock.Add("# Auto-generated by Update-CAHHosts.ps1 on $timestamp")
$newBlock.Add("# Do not edit between these markers - changes will be overwritten.")
$newBlock.Add('')

foreach ($name in ($resolved.Keys | Sort-Object)) {
    $newBlock.Add("# $name")
    foreach ($ip in $resolved[$name]) {
        $newBlock.Add(("{0}`t{1}" -f $ip, $name))
    }
    $newBlock.Add('')
}

if ($BlockHostnames.Count -gt 0) {
    $newBlock.Add('# Telemetry / optional blocks')
    foreach ($name in $BlockHostnames) {
        $newBlock.Add(("0.0.0.0`t{0}" -f $name))
    }
    $newBlock.Add('')
}

$newBlock.Add($EndMarker)

# ---------------------------------------------------------------
# Read current hosts, strip old managed block
# ---------------------------------------------------------------
if (-not (Test-Path -LiteralPath $HostsPath)) {
    Write-Log "Hosts file not found at $HostsPath" 'ERROR'
    exit 1
}

# Backup
$backupName = "hosts-{0}.bak" -f (Get-Date -Format 'yyyyMMdd-HHmmss')
$backupPath = Join-Path $BackupDir $backupName
Copy-Item -LiteralPath $HostsPath -Destination $backupPath -Force
Write-Log "Backed up hosts file to $backupPath"

# Rotate: keep newest 20 backups
Get-ChildItem -LiteralPath $BackupDir -Filter 'hosts-*.bak' |
    Sort-Object LastWriteTime -Descending |
    Select-Object -Skip 20 |
    Remove-Item -Force -ErrorAction SilentlyContinue

$raw = Get-Content -LiteralPath $HostsPath -Raw -ErrorAction Stop

# Remove old managed block (including markers) if present
$pattern = [regex]::Escape($StartMarker) + '.*?' + [regex]::Escape($EndMarker)
$cleaned = [regex]::Replace($raw, $pattern, '', [System.Text.RegularExpressions.RegexOptions]::Singleline)

# Trim trailing whitespace/newlines
$cleaned = $cleaned.TrimEnd() + "`r`n`r`n"

# Append new block
$final = $cleaned + ($newBlock -join "`r`n") + "`r`n"

# ---------------------------------------------------------------
# Write (or simulate)
# ---------------------------------------------------------------
if ($DryRun) {
    Write-Log '--- DRY RUN: hosts file contents that WOULD be written ---'
    Write-Host $final
    Write-Log '--- DRY RUN complete, no changes made ---'
    exit 0
}

# Try to write; if file is locked, retry a few times
$attempts = 0
$maxAttempts = 5
while ($true) {
    try {
        # Preserve original encoding best-effort; hosts is ASCII/UTF-8 no BOM
        $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
        [System.IO.File]::WriteAllText($HostsPath, $final, $utf8NoBom)
        break
    } catch {
        $attempts++
        if ($attempts -ge $maxAttempts) {
            Write-Log "Failed to write hosts file after $maxAttempts attempts: $($_.Exception.Message)" 'ERROR'
            Write-Log "Restoring from backup $backupPath"
            Copy-Item -LiteralPath $backupPath -Destination $HostsPath -Force
            exit 1
        }
        Write-Log "Write failed (attempt $attempts/$maxAttempts): $($_.Exception.Message). Retrying in 2s..." 'WARN'
        Start-Sleep -Seconds 2
    }
}

Write-Log "Hosts file updated with $($resolved.Count) hostnames."

 

Write-Log 'Done.'